const express=require('express');
const cors=require('cors');
const helmet=require('helmet');
const rateLimit=require('express-rate-limit');
require('dotenv').config();
const app=express();
app.use(helmet({contentSecurityPolicy:false}));
app.use(cors({origin:process.env.ALLOWED_ORIGIN||true}));
app.use(express.json({limit:'8mb'}));
app.use('/api/',rateLimit({windowMs:15*60*1000,limit:120,standardHeaders:true,legacyHeaders:false}));
app.get('/api/health',(req,res)=>res.json({ok:true,app:'JASONBOOK',version:'1.0.0',time:new Date().toISOString()}));
app.get('/api/features',(req,res)=>res.json({features:['fil d’actualité','publications','photos/vidéos','stories','amis','groupes','pages','messages','notifications','événements','marketplace','reels/vidéos','lives','sondages','souvenirs','recherche','confidentialité','blocage','mode sombre','langues','accessibilité']}));
app.use((req,res)=>res.status(404).json({error:'Route introuvable'}));
const port=process.env.PORT||3000;
if(require.main===module) app.listen(port,()=>console.log(`JASONBOOK API sur ${port}`));
module.exports=app;
